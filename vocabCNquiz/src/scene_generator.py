            # 1. Question Hero: Chữ Hán to + Pinyin chuẩn
            hz_text = Text(
                hanzi,
                font=CHINESE_FONT,
                font_size=120,
                color="#10b981",
                weight=BOLD
            ).move_to(center_card.get_top() + DOWN * 1.3)
            if hz_text.width > 6.4:
                hz_text.scale_to_fit_width(6.4)

